print("--- 1. Operator Precedence Example ---")
result_1 = 10 + 5 * 2
print("10 + 5 * 2 =", result_1)

result_2 = (10 + 5) * 2
print("(10 + 5) * 2 =", result_2)


print("\n--- 2. Operator Associativity Example ---")
division_result = 20 / 4 * 2
print("20 / 4 * 2 =", division_result)

exponent_result = 2 ** 3 ** 2
print("2 ** 3 ** 2 =", exponent_result)


print("\n--- 3. Logical Operators Precedence ---")
logic_result = True or False and False
print("True or False and False =", logic_result)