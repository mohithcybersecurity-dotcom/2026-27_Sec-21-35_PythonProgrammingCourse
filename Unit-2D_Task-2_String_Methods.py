s = "  Hello Python World  "  # e.g. "  Hello Python World  "

print("Upper:", s.upper())  # s.upper()
print("Lower:", s.lower())  # s.lower()
print("Strip:", s.strip())  # s.strip()
print("Split:", s.split())  # s.split()
print("Join:", "-".join(["Hello", "Python"]))  # "-".join(["Hello", "Python"])
print("Replace:", s.replace("Python", "Java"))  # replace "Python" with "Java"
print("Find:", s.find("Python"))  # find index of "Python"