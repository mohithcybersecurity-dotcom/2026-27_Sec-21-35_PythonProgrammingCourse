s = "Python"  # e.g. "Python"
print("String:", s)

s1 = "Hello"  # e.g. "Hello"
s2 = "World"  # e.g. "World"
print("Concatenation:", s1 + " " + s2)  # join s1 and s2 with a space using +

print("Repetition:", s * 3)  # repeat s three times using *

print("First 3 characters:", s[:3])  # s[:3]
print("Last 3 characters:", s[-3:])  # s[-3:]
print("Characters from index 1 to 4:", s[1:5])  # s[1:5]